def save_report(report):
    """Save generated report to files folder."""

    os.makedirs("data/final/reports", exist_ok=True)

    timestamp = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
    output_path = f"data/final/reports/surf_report_{timestamp}.txt"

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(report)

    print(f"✓ Report saved to {output_path}")
    return output_path


