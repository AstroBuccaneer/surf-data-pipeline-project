import boto3
import json
import os
from datetime import datetime

# AWS config
REGION = "us-east-1"
FINAL_PATH = "data/final/"
PROCESSED_PATH = "data/processed/"

print("✓ Bedrock surf report generator initialized")


def load_surf_data():
    """Load surf scores and predictions for report generation."""

    import pandas as pd

    scores_df = pd.read_csv(f"{PROCESSED_PATH}surf_scores.csv")

    with open(f"{FINAL_PATH}surf_predictions.json", "r") as f:
        predictions = json.load(f)

    with open(f"{FINAL_PATH}model_metadata.json", "r") as f:
        metadata = json.load(f)

    return scores_df, predictions, metadata


def build_report_prompt(scores_df, predictions, metadata):
    """Build prompt for Bedrock report generation."""

    scores_text = ""
    for _, row in scores_df.sort_values("rank").iterrows():
        scores_text += f"#{int(row['rank'])} {row['location_name']} — Score: {row['surf_potential_score']:.2f}\n"

    predictions_text = ""
    for pred in predictions["predictions"]:
        predictions_text += f"{pred['location']}: {pred['predicted_wave_ft']}ft predicted — Surfable: {pred['surfable']}\n"

    prompt = f"""You are a professional surf reporter with deep knowledge of 
oceanography and wave science. Generate a comprehensive surf conditions 
report based on the following data analysis:

HISTORICAL SURF POTENTIAL RANKINGS (2010-2023):
{scores_text}

ML MODEL PREDICTIONS FOR NEXT MONTH:
{predictions_text}

WORLD RECORD BENCHMARKS:
- Largest wave ever recorded: 1,720ft at Lituya Bay Alaska (1958) — caused by magnitude 7.8 earthquake
- Largest wave ever surfed: 86ft at Nazaré Portugal (2020) — surfed by Sebastian Steudtner

MODEL PERFORMANCE:
- Model: {metadata['model_name']}
- R2 Score: {metadata['r2']} (explains {metadata['r2']*100:.1f}% of wave variance)

Please generate a professional surf conditions report covering:
1. Overall rankings summary and what drives each location's score
2. Next month predictions and what surfers should expect
3. Best location recommendations by experience level
4. Historical context comparing to world record benchmarks
5. Key insights from the data analysis

Keep the tone informative but accessible to both surfers and data enthusiasts."""

    return prompt


